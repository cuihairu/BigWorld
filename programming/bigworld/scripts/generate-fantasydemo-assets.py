# The generated marker goes INSIDE the root element of XML assets: the
# XMLSection reader treats text before the first tag as the element's
# attribute list, so a leading '#' or '<!--' line yields an empty parse.
MARKER = ("<!-- Generated by scripts/generate-fantasydemo-assets.py "
          "-- do not edit. -->\n")


def with_marker(content):
    """Puts the generated marker just inside the root element."""
    first_line_end = content.index("\n") + 1
    return content[:first_line_end] + MARKER + content[first_line_end:]


