def main():
    root = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_ROOT

    # Guard against writing the tree into the wrong place: the root must carry
    # the programming/ directory the tree is appended to.
    if not os.path.isdir(os.path.join(root, "programming")):
        print("error: %s does not look like a repository root "
              "(no programming/ directory)" % root)
        return 1

    out_dir = os.path.join(root, OUT_BASE)

    for rel_path, content in FILES:
        # XML assets carry the marker inside the root element; python scripts
        # start with a docstring, so the marker goes on the last line.
        if rel_path.endswith(".xml") or rel_path.endswith(".def"):
            data = with_marker(content)
        else:
            data = content + HEADER
        path = os.path.join(out_dir, rel_path)
        parent = os.path.dirname(path)
        if not os.path.isdir(parent):
            os.makedirs(parent)
        with open(path, "w") as handle:
            handle.write(data)
        print("wrote %s" % os.path.join(OUT_BASE, rel_path))

    print("%d files under %s" % (len(FILES), OUT_BASE))
    return 0


if __name__ == "__main__":
    sys.exit(main())
